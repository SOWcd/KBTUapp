/** The nick in the app's language ("Тихая Лиса", "Тыныш Түлкі", "Quiet Fox"); null for none (a post from before
 * nicks: its `sign` says "Аноним") or indexes this build doesn't know yet (a newer server). */
export function nickName(nick: [number, number] | null | undefined): string | null {
  const a = nick && ADJ[nick[0]], n = nick && NOUN[nick[1]];
  if (!a || !n) return null;
  return i18n.lang === 'kk' ? `${a[1]} ${n[2]}` : i18n.lang === 'en' ? `${a[2]} ${n[3]}` : `${a[0][n[1]]} ${n[0]}`;
}
