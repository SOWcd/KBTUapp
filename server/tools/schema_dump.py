"""Writes schema.current.sql: the database as it is after every migration, for reading (schema.sql is the frozen
start and migrations.py the history; neither alone says what a table has today). Run after adding a migration:
.venv/bin/python tools/schema_dump.py  (tests/test_schema_current.py fails while the file is stale)."""
import sqlite3
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from kbtu import db  # noqa: E402

OUT = Path(__file__).resolve().parent.parent / "kbtu" / "schema.current.sql"
HEAD = "-- Generated by server/tools/schema_dump.py: the schema after every migration. Read this; never edit it.\n"


def dump() -> str:
    with tempfile.TemporaryDirectory() as d:
        path = f"{d}/s.db"
        db.init(path)
        con = sqlite3.connect(path)
        rows = con.execute("""SELECT sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
            ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'view' THEN 2 ELSE 3 END, tbl_name, name""").fetchall()
        con.close()
    return HEAD + "".join(f"{r[0]};\n" for r in rows)


if __name__ == "__main__":
    OUT.write_text(dump())
    print(OUT)
